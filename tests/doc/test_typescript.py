class TestCli:
    def test_stdout(self, capsys):
        rc = main(['doc.ts_models'])
        assert rc == 0
        assert 'export interface Spectrum {' in capsys.readouterr().out

    def test_output_file(self, tmp_path):
        out = tmp_path / 'types.ts'
        rc = main(['doc.ts_models', '-o', str(out)])
        assert rc == 0
        assert 'export interface Spectrum {' in out.read_text()

    def test_check_passes_when_current(self, tmp_path):
        out = tmp_path / 'types.ts'
        main(['doc.ts_models', '-o', str(out)])
        assert main(['doc.ts_models', '-o', str(out), '--check']) == 0

    def test_check_fails_when_stale(self, tmp_path):
        out = tmp_path / 'types.ts'
        out.write_text('// stale\n')
        assert main(['doc.ts_models', '-o', str(out), '--check']) == 1

    def test_check_fails_when_missing(self, tmp_path):
        out = tmp_path / 'nope.ts'
        assert main(['doc.ts_models', '-o', str(out), '--check']) == 1


class TestCustomFieldTypes:
    """A downstream field class can name its own TS type and ship the alias that defines it."""

    def test_ts_type_honours_a_custom_field_class(self):
        from dataclasses import dataclass

        import zeared as z

        @dataclass(frozen=True, kw_only=True, slots=True)
        class Branded(z.Str):
            TS_TYPE = 'Branded'
            TS_PRELUDE = 'export type Branded = string & { readonly __brand: "Branded" };'

        assert ts_type(Branded()) == 'Branded'
        assert ts_type(Branded(many=True)) == 'Branded[]'

        @z.zeared
        class Uses(z.Zeared):
            ref: str | None = Branded(default=None)
            other: str = Branded(required=True)

        out = emit([Uses])
        assert out.count('export type Branded = string') == 1  # the prelude, once
        assert out.index('export type Branded') < out.index('export interface Uses')
        assert '  ref?: Branded | null;' in out
        assert '  other: Branded;' in out


class TestDefaultRead:
    """Pin (0.3.8): nullability reads ``f.default``, with ``missing`` only as
    a fallback, so a defaulted optional field stays non-nullable once seared
    0.4.0 removes the ``missing`` slot."""

    def test_default_without_missing_slot_is_not_nullable(self):
        from types import SimpleNamespace

        from zeared.doc.typescript import _member

        # Shaped like a seared 0.4.0 field: a default, and no ``missing``.
        f = SimpleNamespace(required=False, default=5, default_factory=None, doc=None)
        assert _member('n', 'n', f) == ['  n?: unknown;']

    def test_no_default_is_nullable(self):
        from types import SimpleNamespace

        from zeared.doc.typescript import _member

        f = SimpleNamespace(required=False, default=None, default_factory=None, doc=None)
        assert _member('n', 'n', f) == ['  n?: unknown | null;']
